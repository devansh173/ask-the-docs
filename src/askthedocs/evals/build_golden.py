"""Helper for authoring and validating the golden set.

    python -m askthedocs.evals.build_golden --validate
        Check every entry: does the labelled page exist in the corpus, does the
        question retrieve anything, are the ids unique.

    python -m askthedocs.evals.build_golden --candidates qdrant --limit 30
        List indexed pages with their headings, to write questions against.

The golden set is written by hand rather than generated by a model. Generating
questions with an LLM and then scoring the pipeline with an LLM measures how
self-consistent one model is; hand-written references measure the system. It is
slower and it is the reason the numbers mean anything.
"""

from __future__ import annotations

import argparse
import logging
import sys
from collections import defaultdict

from ..config import RAW_DIR, settings
from ..logging_setup import setup as setup_logging
from ..retrieval import store
from . import golden

log = logging.getLogger(__name__)


def list_candidates(doc_set: str | None, limit: int) -> None:
    """Print indexed pages and their section headings."""
    directories = [p for p in RAW_DIR.iterdir() if p.is_dir()]
    if doc_set:
        directories = [p for p in directories if p.name == doc_set]

    for directory in directories:
        print(f"\n{'=' * 78}\n{directory.name}\n{'=' * 78}")
        for path in sorted(directory.glob("*.md"))[:limit]:
            text = path.read_text(encoding="utf-8")
            url = next(
                (l[5:].strip() for l in text.splitlines()[:6] if l.startswith("url:")),
                "",
            )
            title = next(
                (l[7:].strip().strip('"') for l in text.splitlines()[:6]
                 if l.startswith("title:")),
                path.stem,
            )
            headings = [
                l.lstrip("# ").strip()
                for l in text.splitlines()
                if l.startswith("## ") and len(l) < 90
            ][:6]
            print(f"\n  {title}\n  {url}")
            for h in headings:
                print(f"    - {h}")


def validate() -> int:
    """Check the golden set against the corpus. Returns a process exit code."""
    items = golden.load()
    problems: list[str] = []

    # Every labelled URL must exist in the scraped corpus.
    corpus_urls: set[str] = set()
    for path in RAW_DIR.rglob("*.md"):
        for line in path.read_text(encoding="utf-8").splitlines()[:6]:
            if line.startswith("url:"):
                corpus_urls.add(line[4:].strip())
                break

    seen_ids: set[str] = set()
    for item in items:
        if item.id in seen_ids:
            problems.append(f"{item.id}: duplicate id")
        seen_ids.add(item.id)

        if item.answerable:
            if not item.relevant_urls:
                problems.append(f"{item.id}: answerable but has no relevant_urls")
            if not item.reference_answer.strip():
                problems.append(f"{item.id}: answerable but has no reference answer")
            for url in item.relevant_urls:
                if corpus_urls and url not in corpus_urls:
                    problems.append(f"{item.id}: labelled url not in corpus -> {url}")
        else:
            if item.relevant_urls:
                problems.append(f"{item.id}: out-of-scope but carries relevance labels")

    # Sanity-check that answerable questions actually retrieve their page.
    unreachable: list[str] = []
    try:
        if store.collection_size(settings):
            for item in items:
                if not item.answerable or not item.relevant_urls:
                    continue
                hits = store.search(settings, item.question, limit=10).hits
                urls = {h.source_url for h in hits}
                if not urls & set(item.relevant_urls):
                    unreachable.append(item.id)
    except Exception as exc:
        log.warning("could not check retrievability: %s", exc)

    stats = golden.stats(items)
    print("\nGolden set")
    print(f"  total              {stats['total']}")
    print(f"  answerable         {stats['answerable']}")
    print(f"  out of scope       {stats['out_of_scope']}")
    print(f"  by doc set         {stats['by_doc_set']}")
    print(f"  by kind            {stats['by_kind']}")

    if unreachable:
        print(
            f"\n  {len(unreachable)} question(s) whose labelled page is not in the "
            f"top 10: {', '.join(unreachable[:12])}"
        )
        print("  (expected for a few hard questions - this is the headroom the "
              "eval is meant to expose, not necessarily a labelling error)")

    if problems:
        print(f"\n{len(problems)} problem(s):")
        for p in problems:
            print(f"  - {p}")
        return 1

    print("\nno structural problems found")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--validate", action="store_true")
    parser.add_argument("--candidates", nargs="?", const="", default=None,
                        help="list pages for a doc set (or all)")
    parser.add_argument("--limit", type=int, default=40)
    args = parser.parse_args(argv)

    setup_logging()
    if args.candidates is not None:
        list_candidates(args.candidates or None, args.limit)
        return 0
    return validate()


if __name__ == "__main__":
    sys.exit(main())
